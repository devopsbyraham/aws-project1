# ----------------------------------------------------------------------------
# State helpers
# ----------------------------------------------------------------------------
record() {
  local key="$1" value="${2:-}" escaped
  escaped="$(printf '%q' "$value")"
  touch "$STATE_FILE"
  if grep -qE "^${key}=" "$STATE_FILE" 2>/dev/null; then
    awk -v k="$key" -v v="$escaped" 'BEGIN{FS=OFS="="} $1==k {$0=k"="v} {print}' \
      "$STATE_FILE" > "${STATE_FILE}.tmp"
    mv "${STATE_FILE}.tmp" "$STATE_FILE"
  else
    printf '%s=%s\n' "$key" "$escaped" >> "$STATE_FILE"
  fi
}

load_state() {
  [[ -f "$STATE_FILE" ]] || return 0
  # State is generated by this script with printf %q.
  # shellcheck disable=SC1090
  source "$STATE_FILE"
}

