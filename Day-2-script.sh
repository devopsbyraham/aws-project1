  "ViewerCertificate": {
    "CloudFrontDefaultCertificate": true,
    "MinimumProtocolVersion": "TLSv1.2_2021"
  }
}
JSON_CF

    # Validate the exact configuration that will be submitted.
    if ! jq -e '.Origins.Items[1].CustomOriginConfig.OriginSslProtocols |
        type == "object" and .Quantity == 1 and (.Items | type == "array") and .Items[0] == "TLSv1.2"' \
        "$CF_CONFIG" >/dev/null 2>&1; then
      echo "[FAIL] Invalid CloudFront JSON: OriginSslProtocols is not the required object shape." >&2
      jq '.Origins.Items[1].CustomOriginConfig.OriginSslProtocols' "$CF_CONFIG" >&2 || true
      die "CloudFront configuration validation failed before AWS API call."
    fi

    log "Creating CloudFront distribution..."
    set +e
    CF_OUTPUT="$(aws cloudfront create-distribution \
      --distribution-config "file://$CF_CONFIG" 2>&1)"
    CF_RC=$?
    set -e

    if [[ "$CF_RC" -ne 0 ]]; then
      if grep -qiE 'account must be verified|account.*verified|verify your account|account verification' <<<"$CF_OUTPUT"; then
        warn "AWS account verification is blocking CloudFront creation."
        warn "This is an AWS account-level restriction; changing IAM or the CLI command will not bypass it."
        warn "Continuing with S3, EFS and EBS so Day 2 does not fail halfway."
        CF_ID=""
        CF_ARN=""
        CF_DOMAIN=""
      else
        printf '%s\n' "$CF_OUTPUT" >&2
        die "CloudFront distribution creation failed."
      fi
    else
      if command -v jq >/dev/null 2>&1; then
        CF_ID="$(jq -r '.Distribution.Id // empty' <<<"$CF_OUTPUT")"
        CF_ARN="$(jq -r '.Distribution.ARN // empty' <<<"$CF_OUTPUT")"
        CF_DOMAIN="$(jq -r '.Distribution.DomainName // empty' <<<"$CF_OUTPUT")"
      else
        CF_ID="$(aws cloudfront list-distributions \
          --query "DistributionList.Items[?Comment=='$PROJECT-CDN'].Id | [0]" \
          --output text)"
        CF_ARN="$(aws cloudfront get-distribution --id "$CF_ID" --query 'Distribution.ARN' --output text)"
        CF_DOMAIN="$(aws cloudfront get-distribution --id "$CF_ID" --query 'Distribution.DomainName' --output text)"
      fi
      ok "CloudFront created: $CF_ID ($CF_DOMAIN)"
    fi
  fi
fi

