done

# ----------------------------------------------------------------------------
# AWS lookup helpers
# ----------------------------------------------------------------------------
first_or_empty() {
  local value="$1"
  [[ "$value" == "None" || "$value" == "null" ]] && value=""
  printf '%s' "$value"
}

# AWS CLI waiter commands are not available in every installed CLI build.
# Poll resource state directly so the script works across AWS CLI versions.
wait_efs_available() {
  local fs_id="$1" state i
  for i in $(seq 1 60); do
    state="$(aws efs describe-file-systems --region "$REGION" --file-system-id "$fs_id" --query 'FileSystems[0].LifeCycleState' --output text 2>/dev/null || true)"
    state="$(first_or_empty "$state")"
    [[ "$state" == "available" ]] && return 0
    [[ "$state" == "deleting" || "$state" == "deleted" ]] && return 1
    sleep 2
  done
  return 1
}

wait_efs_mount_target_available() {
  local mt_id="$1" state i
  for i in $(seq 1 90); do
    state="$(aws efs describe-mount-targets --region "$REGION" --mount-target-id "$mt_id" --query 'MountTargets[0].LifeCycleState' --output text 2>/dev/null || true)"
    state="$(first_or_empty "$state")"
    [[ "$state" == "available" ]] && return 0
    [[ "$state" == "error" || "$state" == "deleting" || "$state" == "deleted" ]] && return 1
    sleep 2
  done
  return 1
}

wait_volume_state() {
  local volume_id="$1" desired="$2" state i
  for i in $(seq 1 60); do
    state="$(aws ec2 describe-volumes --region "$REGION" --volume-ids "$volume_id" --query 'Volumes[0].State' --output text 2>/dev/null || true)"
    state="$(first_or_empty "$state")"
    [[ "$state" == "$desired" ]] && return 0
    [[ "$state" == "error" || "$state" == "deleted" ]] && return 1
    sleep 2
  done
  return 1
}

wait_cloudfront_deployed() {
  local dist_id="$1" status i
  for i in $(seq 1 180); do
    status="$(aws cloudfront get-distribution --id "$dist_id" --query 'Distribution.Status' --output text 2>/dev/null || true)"
    status="$(first_or_empty "$status")"
    [[ "$status" == "Deployed" ]] && return 0
    sleep 10
  done
  return 1
}

# Resolve a subnet reliably even when the Day 1 state file is stale or the
# Name tag differs from the expected value. We first use the Name tag, then
# fall back to the exact VPC + CIDR + AZ combination. If the subnet is truly
# missing, we create the Day 1-required subnet so Day 2 can continue.
resolve_subnet() {
  # resolve_subnet <vpc-id> <name-tag> <cidr> <az>
  local vpc="$1" name="$2" cidr="$3" az="$4" id=""

  id="$(aws ec2 describe-subnets \
    --filters "Name=vpc-id,Values=$vpc" "Name=tag:Name,Values=$name" \
    --query 'Subnets[0].SubnetId' --output text 2>/dev/null || true)"
  id="$(first_or_empty "$id")"

  if [[ -z "$id" ]]; then
    id="$(aws ec2 describe-subnets \
      --filters "Name=vpc-id,Values=$vpc" "Name=cidr-block,Values=$cidr" "Name=availability-zone,Values=$az" \
      --query 'Subnets[0].SubnetId' --output text 2>/dev/null || true)"
    id="$(first_or_empty "$id")"
  fi

  if [[ -z "$id" ]]; then
    log "Day 1 subnet $name ($cidr / $az) is missing; creating it now."
    id="$(aws ec2 create-subnet \
      --vpc-id "$vpc" \
      --cidr-block "$cidr" \
      --availability-zone "$az" \
      --tag-specifications "ResourceType=subnet,Tags=[{Key=Name,Value=$name},{Key=Project,Value=$PROJECT}]" \
      --query 'Subnet.SubnetId' --output text)"
    id="$(first_or_empty "$id")"
  fi

  [[ -n "$id" ]] || die "Unable to resolve or create subnet '$name' ($cidr in $az)."
  printf '%s' "$id"
}

