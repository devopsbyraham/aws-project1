create_mount_target() {
  local subnet="$1" az="$2" mt_id ip

  mt_id="$(aws efs describe-mount-targets --region "$REGION" --file-system-id "$EFS_ID" \
    --query "MountTargets[?SubnetId=='$subnet'].MountTargetId | [0]" \
    --output text 2>/dev/null || true)"
  mt_id="$(first_or_empty "$mt_id")"

  if [[ -n "$mt_id" ]]; then
    ok "EFS mount target already exists in $az: $mt_id"
  else
    mt_id="$(aws efs create-mount-target --region "$REGION" \
      --file-system-id "$EFS_ID" \
      --subnet-id "$subnet" \
      --security-groups "$SG_EFS" \
      --query MountTargetId --output text)"
    ok "Created EFS mount target in $az: $mt_id"
  fi

  wait_efs_mount_target_available "$mt_id" || die "EFS mount target $mt_id in $az did not become available."

  ip="$(aws efs describe-mount-targets --region "$REGION" --mount-target-id "$mt_id" \
    --query 'MountTargets[0].IpAddress' --output text)"
  ip="$(first_or_empty "$ip")"
  [[ -n "$ip" ]] || die "Could not determine EFS mount target IP for $mt_id ($az)."

  printf '%s|%s|%s\n' "$az" "$mt_id" "$ip"
}

